"""The systemd user timer that starts `flakipype run`: unit files, install, uninstall, status."""

import re
import subprocess
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

SERVICE = "flakipype.service"
TIMER = "flakipype.timer"
GENERATED = "generated by flakipype"
# A unit file line must not be able to smuggle in more settings.
_SAFE_PATH = re.compile(r"^/[A-Za-z0-9/._+-]+$")
_CONTROL = re.compile(r"[\x00-\x1f\x7f]")
_STOP_MARGIN_MINUTES = 10
_COMMAND_SECONDS = 600
_NOT_FOUND = 127


class DaemonError(Exception):
    """The timer could not be installed or removed; the message says why and what exists."""


@dataclass(frozen=True)
class CommandResult:
    code: int
    output: str


class CommandRunner(Protocol):
    def __call__(self, arguments: list[str]) -> CommandResult: ...


def run_command(arguments: list[str]) -> CommandResult:
    """Runs a program without a shell; output and errors together, as a person would see them."""
    try:
        done = subprocess.run(  # noqa: S603 - fixed programs, arguments validated by the caller
            arguments,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            check=False,
            timeout=_COMMAND_SECONDS,
        )
    except FileNotFoundError:
        return CommandResult(_NOT_FOUND, f"{arguments[0]} is not installed")
    return CommandResult(done.returncode, (done.stdout + done.stderr).strip())


def installed_executable(argv0: str, which: Callable[[str], str | None]) -> Path:
    """The absolute path of the running flakipype command, for ExecStart."""
    found = argv0 if "/" in argv0 else which(argv0)
    path = Path(found or argv0).absolute()
    if path.name != "flakipype":
        message = "Run `flakipype daemon install` with the installed flakipype command."
        raise DaemonError(message)
    return path


@dataclass(frozen=True)
class UnitOptions:
    executable: Path
    schedule: str
    mode: str
    run_minutes: int


def render_units(options: UnitOptions) -> dict[str, str]:
    executable = options.executable.as_posix()
    if not _SAFE_PATH.match(executable):
        message = f"{executable} contains characters a unit file cannot hold safely"
        raise DaemonError(message)
    if _CONTROL.search(options.schedule) or _CONTROL.search(options.mode):
        message = "The schedule must be a single line"
        raise DaemonError(message)
    timeout = options.run_minutes + _STOP_MARGIN_MINUTES
    service = (
        f"# {SERVICE}, {GENERATED}\n[Unit]\n"
        "Description=flakipype: find and fix flaky GitHub Actions pipelines\n\n"
        f"[Service]\nType=oneshot\nExecStart={executable} run --mode {options.mode}\n"
        f"TimeoutStartSec={timeout}min\nNice=10\n"
    )
    timer = (
        f"# {TIMER}, {GENERATED}\n[Unit]\nDescription=Run flakipype on a schedule\n\n"
        f"[Timer]\nOnCalendar={options.schedule}\nRandomizedDelaySec=15min\nPersistent=true\n\n"
        "[Install]\nWantedBy=timers.target\n"
    )
    return {SERVICE: service, TIMER: timer}


class Daemon:
    def __init__(self, *, unit_dir: Path, run: CommandRunner, user: str) -> None:
        self._unit_dir = unit_dir
        self._run = run
        self._user = user

    @property
    def unit_dir(self) -> Path:
        return self._unit_dir

    def install(self, options: UnitOptions) -> list[str]:
        """Checks, writes and starts the timer; returns warnings. A failed check changes nothing."""
        units = render_units(options)
        self._must("systemd-analyze", "calendar", options.schedule)
        self._check_doctor(options.executable)
        foreign = [name for name in units if self._exists_foreign(name)]
        if foreign:
            message = (
                f"{', '.join(foreign)} in {self._unit_dir} were not written by flakipype; "
                "they are left as they are."
            )
            raise DaemonError(message)
        self._unit_dir.mkdir(parents=True, exist_ok=True)
        for name, text in units.items():
            (self._unit_dir / name).write_text(text, encoding="utf-8")
        try:
            self._must("systemctl", "--user", "daemon-reload")
            self._must("systemctl", "--user", "enable", "--now", TIMER)
        except DaemonError as error:
            message = (
                f"{error}\nThe unit files are in {self._unit_dir}; "
                "`flakipype daemon uninstall` removes them."
            )
            raise DaemonError(message) from error
        return self._linger_warnings()

    def uninstall(self) -> list[str]:
        """Stops the timer and removes the units flakipype wrote; returns their names."""
        ours = [name for name in (TIMER, SERVICE) if self._exists_ours(name)]
        if TIMER in ours:
            self._must("systemctl", "--user", "disable", "--now", TIMER)
        for name in ours:
            (self._unit_dir / name).unlink()
        if ours:
            self._must("systemctl", "--user", "daemon-reload")
        return ours

    def status(self) -> str:
        if not self._exists_ours(TIMER):
            return "The timer is not installed. `flakipype daemon install` sets it up."
        timers = self._run(["systemctl", "--user", "list-timers", TIMER, "--all", "--no-pager"])
        result = self._run(
            ["systemctl", "--user", "show", SERVICE, "--property=Result,ExecMainStatus"]
        )
        journal = self._run(
            ["journalctl", "--user", "--unit", SERVICE, "--lines", "20", "--no-pager",
             "--output", "cat"]
        )  # fmt: skip
        return f"{timers.output}\n\n{result.output}\n\nLast run:\n{journal.output}"

    def _check_doctor(self, executable: Path) -> None:
        checked = self._run(
            ["systemd-run", "--user", "--wait", "--pipe", "--collect", "--quiet",
             executable.as_posix(), "doctor"]
        )  # fmt: skip
        if checked.code != 0:
            message = (
                "`flakipype doctor` failed in the environment the timer runs in, so nothing was "
                f"installed:\n{checked.output}"
            )
            raise DaemonError(message)

    def _linger_warnings(self) -> list[str]:
        linger = self._run(["loginctl", "show-user", self._user, "--property=Linger", "--value"])
        if linger.output.strip() == "yes":
            return []
        return [
            (
                "The timer only runs while you are logged in. `loginctl enable-linger` lets it "
                "run without a login session."
            )
        ]

    def _must(self, *arguments: str) -> None:
        result = self._run(list(arguments))
        if result.code != 0:
            message = f"`{' '.join(arguments)}` failed: {result.output}"
            raise DaemonError(message)

    def _exists_ours(self, name: str) -> bool:
        path = self._unit_dir / name
        return path.exists() and GENERATED in path.read_text(encoding="utf-8")

    def _exists_foreign(self, name: str) -> bool:
        return (self._unit_dir / name).exists() and not self._exists_ours(name)
