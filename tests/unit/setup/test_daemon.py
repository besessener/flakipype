import sys
from pathlib import Path

import pytest

from flakipype.setup.daemon import (
    SERVICE,
    TIMER,
    CommandResult,
    Daemon,
    DaemonError,
    UnitOptions,
    installed_executable,
    render_units,
    run_command,
)

from support.fake_daemon import FakeRunner

EXECUTABLE = Path("/home/me/.local/bin/flakipype")
OPTIONS = UnitOptions(executable=EXECUTABLE, schedule="daily", mode="auto")


def daemon(tmp_path: Path, runner: FakeRunner) -> Daemon:
    return Daemon(unit_dir=tmp_path / "systemd" / "user", run=runner, user="me")


def test_the_units_run_flakipype_once_on_the_schedule() -> None:
    units = render_units(OPTIONS)

    assert units[SERVICE] == (
        "# flakipype.service, generated by flakipype\n[Unit]\n"
        "Description=flakipype: find and fix flaky GitHub Actions pipelines\n\n"
        "[Service]\nType=oneshot\nExecStart=/home/me/.local/bin/flakipype run --mode auto\n"
        "TimeoutStartSec=730min\nNice=10\n"
    )
    assert units[TIMER] == (
        "# flakipype.timer, generated by flakipype\n[Unit]\nDescription=Run flakipype on a "
        "schedule\n\n[Timer]\nOnCalendar=daily\nRandomizedDelaySec=15min\nPersistent=true\n\n"
        "[Install]\nWantedBy=timers.target\n"
    )


@pytest.mark.parametrize(
    ("options", "problem"),
    [
        (UnitOptions(Path("/home/me/my bin/flakipype"), "daily", "auto"), "cannot hold"),
        (UnitOptions(EXECUTABLE, "daily\nExecStart=/bin/sh", "auto"), "single line"),
    ],
)
def test_nothing_can_be_smuggled_into_a_unit(options: UnitOptions, problem: str) -> None:
    with pytest.raises(DaemonError, match=problem):
        render_units(options)


def test_install_checks_then_writes_and_starts_the_timer(tmp_path: Path) -> None:
    runner = FakeRunner({"loginctl": CommandResult(0, "yes\n")})
    service = daemon(tmp_path, runner)

    warnings = service.install(OPTIONS)

    assert warnings == []
    assert runner.calls == [
        "systemd-analyze calendar daily",
        "systemd-run --user --wait --pipe --collect --quiet /home/me/.local/bin/flakipype doctor",
        "systemctl --user daemon-reload",
        "systemctl --user enable --now flakipype.timer",
        "loginctl show-user me --property=Linger --value",
    ]
    assert (service.unit_dir / TIMER).read_text(encoding="utf-8") == render_units(OPTIONS)[TIMER]


def test_install_warns_without_lingering(tmp_path: Path) -> None:
    warnings = daemon(tmp_path, FakeRunner({"loginctl": CommandResult(0, "no")})).install(OPTIONS)

    assert warnings == [
        (
            "The timer only runs while you are logged in. `loginctl enable-linger` lets it run "
            "without a login session."
        )
    ]


@pytest.mark.parametrize(
    ("command", "problem"),
    [
        ("systemd-analyze", "`systemd-analyze calendar daily` failed: bad calendar"),
        ("systemd-run", "`flakipype doctor` failed in the environment the timer runs in"),
    ],
)
def test_a_failed_check_installs_nothing(tmp_path: Path, command: str, problem: str) -> None:
    service = daemon(tmp_path, FakeRunner({command: CommandResult(1, "bad calendar")}))

    with pytest.raises(DaemonError, match=problem):
        service.install(OPTIONS)
    assert not service.unit_dir.exists()


def test_units_flakipype_did_not_write_are_left_alone(tmp_path: Path) -> None:
    runner = FakeRunner()
    service = daemon(tmp_path, runner)
    service.unit_dir.mkdir(parents=True)
    (service.unit_dir / TIMER).write_text("[Timer]\nOnCalendar=hourly\n", encoding="utf-8")

    with pytest.raises(DaemonError, match=r"flakipype\.timer in .+ were not written by"):
        service.install(OPTIONS)
    assert service.uninstall() == []
    assert (service.unit_dir / TIMER).read_text(encoding="utf-8").startswith("[Timer]")
    assert not (service.unit_dir / SERVICE).exists()


def test_a_failed_start_says_where_the_units_are(tmp_path: Path) -> None:
    runner = FakeRunner({"systemctl --user enable": CommandResult(1, "Failed to connect to bus")})

    with pytest.raises(DaemonError, match="Failed to connect to bus\nThe unit files are in"):
        daemon(tmp_path, runner).install(OPTIONS)


def test_uninstall_stops_and_removes_the_units(tmp_path: Path) -> None:
    runner = FakeRunner()
    service = daemon(tmp_path, runner)
    service.install(OPTIONS)
    runner.calls.clear()

    removed = service.uninstall()

    assert removed == [TIMER, SERVICE]
    assert list(service.unit_dir.iterdir()) == []
    assert runner.calls == [
        "systemctl --user disable --now flakipype.timer",
        "systemctl --user daemon-reload",
    ]


def test_status_shows_the_timer_and_the_last_run(tmp_path: Path) -> None:
    runner = FakeRunner({
        "systemctl --user list-timers": CommandResult(0, "NEXT Tue 06:07 flakipype.timer"),
        "systemctl --user show": CommandResult(0, "Result=success\nExecMainStatus=0"),
        "journalctl": CommandResult(0, "flakipype run · octo-org · auto"),
    })  # fmt: skip
    service = daemon(tmp_path, runner)

    before = service.status()
    service.install(OPTIONS)

    assert before == "The timer is not installed. `flakipype daemon install` sets it up."
    assert service.status() == (
        "NEXT Tue 06:07 flakipype.timer\n\nResult=success\nExecMainStatus=0\n\n"
        "Last run:\nflakipype run · octo-org · auto"
    )


def test_commands_run_without_a_shell() -> None:
    done = run_command([sys.executable, "-c", "import sys; print('out'); sys.exit(3)"])
    missing = run_command(["flakipype-no-such-program"])

    assert (done.code, done.output) == (3, "out")
    assert (missing.code, missing.output) == (127, "flakipype-no-such-program is not installed")


def test_the_executable_is_the_installed_command(tmp_path: Path) -> None:
    found = tmp_path / "flakipype"

    assert installed_executable("flakipype", lambda _: str(found)) == found
    assert installed_executable(str(found), lambda _: None) == found
    with pytest.raises(DaemonError, match="with the installed flakipype command"):
        installed_executable("/usr/lib/python3/flakipype/__main__.py", lambda _: None)
